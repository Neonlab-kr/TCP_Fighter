    internal sealed class CodeWriter
    {
        private readonly StringBuilder _builder = new StringBuilder();
        private readonly string _indentText;
        private int _indent;

        public CodeWriter() : this("    ") { }
        public CodeWriter(string indentText) { _indentText = indentText; }
        public void Indent() { ++_indent; }
        public void Unindent() { if (_indent > 0) --_indent; }
        public void BeginBlock() { Line("{"); Indent(); }
        public void EndBlock() { Unindent(); Line("}"); }
        public void EndBlock(string suffix) { Unindent(); Line("}" + suffix); }
        public void Line() { _builder.AppendLine(); }
        public void Line(string text)
        {
            for (int i = 0; i < _indent; ++i)
                _builder.Append(_indentText);
            _builder.AppendLine(text);
        }
        public override string ToString() { return _builder.ToString(); }
    }

    internal static class PathUtil
    {
        public static string FindRoot(string protocolRelativePath)
        {
            DirectoryInfo dir = new DirectoryInfo(AppDomain.CurrentDomain.BaseDirectory);
            while (dir != null)
            {
                if (File.Exists(Combine(dir.FullName, protocolRelativePath)))
                    return dir.FullName;
                dir = dir.Parent;
            }
            throw new Exception("Solution root not found. Expected file: " + protocolRelativePath);
        }
        public static string Combine(string root, string relativePath)
        {
            return Path.Combine(root, relativePath.Replace('/', Path.DirectorySeparatorChar));
        }
        public static void EnsureParentDirectory(string filePath)
        {
            string dir = Path.GetDirectoryName(Path.GetFullPath(filePath));
            if (!string.IsNullOrEmpty(dir) && !Directory.Exists(dir))
                Directory.CreateDirectory(dir);
        }
    }

    internal static class TextUtil
    {
        public static string StripComment(string line)
        {
            int slash = line.IndexOf("//", StringComparison.Ordinal);
            int hash = line.IndexOf('#');
            int cut = -1;
            if (slash >= 0) cut = slash;
            if (hash >= 0 && (cut < 0 || hash < cut)) cut = hash;
            return cut >= 0 ? line.Substring(0, cut) : line;
        }
        public static string TrimStatement(string text)
        {
            text = text.Trim();
            if (text.EndsWith(";", StringComparison.Ordinal))
                text = text.Substring(0, text.Length - 1).Trim();
            return text;
        }
        public static int ParseIntLiteral(string text, int lineNumber)
        {
            long value = ParseLongLiteral(text, lineNumber);
            if (value < int.MinValue || value > int.MaxValue)
                throw new Exception("Line " + lineNumber + ": number is out of int range: " + text);
            return (int)value;
        }

        public static long ParseLongLiteral(string text, int lineNumber)
        {
            long value;
            if (text.StartsWith("0x", StringComparison.OrdinalIgnoreCase))
            {
                if (!long.TryParse(text.Substring(2), NumberStyles.HexNumber, CultureInfo.InvariantCulture, out value))
                    throw new Exception("Line " + lineNumber + ": invalid hex number: " + text);
                return value;
            }
            if (!long.TryParse(text, NumberStyles.Integer, CultureInfo.InvariantCulture, out value))
                throw new Exception("Line " + lineNumber + ": invalid number: " + text);
            return value;
        }
        public static int IndexOfWhiteSpace(string text, int start)
        {
            for (int i = start; i < text.Length; ++i)
            {
                if (char.IsWhiteSpace(text[i])) return i;
            }
            return -1;
        }
        public static string[] SplitByComma(string text)
        {
            List<string> list = new List<string>();
            int start = 0;
            for (int i = 0; i < text.Length; ++i)
            {
                if (text[i] == ',')
                {
                    list.Add(text.Substring(start, i - start));
                    start = i + 1;
                }
            }
            list.Add(text.Substring(start));
            return list.ToArray();
        }
        public static string[] SplitByWhiteSpace(string text)
        {
            List<string> list = new List<string>();
            int i = 0;
            while (i < text.Length)
            {
                while (i < text.Length && char.IsWhiteSpace(text[i])) ++i;
                if (i >= text.Length) break;
                int start = i;
                while (i < text.Length && !char.IsWhiteSpace(text[i])) ++i;
                list.Add(text.Substring(start, i - start));
            }
            return list.ToArray();
        }
        public static bool IsIdentifier(string text)
        {
            if (string.IsNullOrEmpty(text)) return false;
            if (!(char.IsLetter(text[0]) || text[0] == '_')) return false;
            for (int i = 1; i < text.Length; ++i)
            {
                char ch = text[i];
                if (!(char.IsLetterOrDigit(ch) || ch == '_')) return false;
            }
            return true;
        }
        public static string ToSnakeUpper(string text)
        {
            StringBuilder b = new StringBuilder();
            for (int i = 0; i < text.Length; ++i)
            {
                char ch = text[i];
                if (char.IsUpper(ch) && i > 0)
                {
                    char prev = text[i - 1];
                    if (char.IsLower(prev) || char.IsDigit(prev)) b.Append('_');
                }
                b.Append(char.ToUpperInvariant(ch));
            }
            return b.ToString();
        }
    }
