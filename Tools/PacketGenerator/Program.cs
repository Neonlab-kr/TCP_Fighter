    internal sealed class TypeInfo
    {
        public readonly string IdlName;
        public readonly string CppType;
        public readonly string CsType;
        public readonly string CsWrite;
        public readonly string CsRead;
        public readonly int Size;
        public readonly long MaxValue;

        public TypeInfo(string idlName, string cppType, string csType, string csWrite, string csRead, int size, long maxValue)
        {
            IdlName = idlName;
            CppType = cppType;
            CsType = csType;
            CsWrite = csWrite;
            CsRead = csRead;
            Size = size;
            MaxValue = maxValue;
        }
    }

    internal sealed class ProtocolSettings
    {
        public int PacketCode = -1;
        public TypeInfo PacketTypeType;
        public TypeInfo PayloadSizeType;
        public int MaxPayloadSize = -1;

        public int HeaderSize
        {
            get { return 1 + PayloadSizeType.Size + PacketTypeType.Size; }
        }

        public string PacketCodeHex
        {
            get { return "0x" + PacketCode.ToString("X2", CultureInfo.InvariantCulture); }
        }
    }

    internal sealed class FieldDef
    {
        public string TypeName;
        public string Name;
        public TypeInfo Type;
        public bool AutoGenerated;
    }

    internal sealed class ConstDef
    {
        public string TypeName;
        public string Name;
        public TypeInfo Type;
        public long Value;
    }

    internal sealed class PacketDef
    {
        public string Direction;
        public string Name;
        public int Id;
        public readonly List<FieldDef> DeclaredFields = new List<FieldDef>();
        public readonly List<FieldDef> WireFields = new List<FieldDef>();

        public bool IsC2S { get { return Direction == "c2s"; } }
        public bool IsS2C { get { return Direction == "s2c"; } }
        public string DirectionUpper { get { return Direction.ToUpperInvariant(); } }
        public string NameUpper { get { return TextUtil.ToSnakeUpper(Name); } }
        public string Symbol { get { return DirectionUpper + "_" + NameUpper; } }

        public int PayloadSize
        {
            get
            {
                int size = 0;
                for (int i = 0; i < WireFields.Count; ++i)
                    size += WireFields[i].Type.Size;
                return size;
            }
        }
    }

    internal sealed class ProtocolDef
    {
        public readonly ProtocolSettings Settings = new ProtocolSettings();
        public readonly List<ConstDef> Constants = new List<ConstDef>();
        public readonly List<PacketDef> Packets = new List<PacketDef>();

        public List<PacketDef> GetPackets(string direction)
        {
            List<PacketDef> result = new List<PacketDef>();
            for (int i = 0; i < Packets.Count; ++i)
            {
                if (Packets[i].Direction == direction)
                    result.Add(Packets[i]);
            }
            return result;
        }
    }

    internal static class Program
    {
        private const string ServerGameRelativePath = "TCP_FIGHTER/Game";
        private const string ClientGeneratedRelativePath = "Client/Generated/RPC";
        private const string ProtocolRelativePath = "Tools/PacketGenerator/Protocol/GameProtocol.IDL";

        private static readonly Dictionary<string, TypeInfo> Types = CreateTypeMap();

        private static int Main(string[] args)
        {
            try
            {
                string root = PathUtil.FindRoot(ProtocolRelativePath);
                string protocolPath = PathUtil.Combine(root, ProtocolRelativePath);
                string serverRpcPath = Path.Combine(PathUtil.Combine(root, ServerGameRelativePath), "RPC");
                string clientRpcPath = PathUtil.Combine(root, ClientGeneratedRelativePath);

                ProtocolDef protocol = ProtocolParser.Parse(protocolPath, Types);
                ProtocolValidator.Validate(protocol);

                WriteFile(Path.Combine(serverRpcPath, "RPCCommon.h"), CppGenerator.GenerateCommon(protocol));
                WriteFile(Path.Combine(serverRpcPath, "C2S_Stub.h"), CppGenerator.GenerateC2SStub(protocol));
                WriteFile(Path.Combine(serverRpcPath, "S2C_Proxy.h"), CppGenerator.GenerateS2CProxy(protocol));

                WriteFile(Path.Combine(clientRpcPath, "RPCCommon.cs"), CSharpGenerator.GenerateCommon(protocol));
                WriteFile(Path.Combine(clientRpcPath, "C2S_Proxy.cs"), CSharpGenerator.GenerateC2SProxy(protocol));
                WriteFile(Path.Combine(clientRpcPath, "S2C_Stub.cs"), CSharpGenerator.GenerateS2CStub(protocol));

                Console.WriteLine("RPC PacketGenerator completed.");
                Console.WriteLine("Protocol   : " + protocolPath);
                Console.WriteLine("Server RPC : " + serverRpcPath);
                Console.WriteLine("Client RPC : " + clientRpcPath);
                Console.WriteLine("Packet Count: " + protocol.Packets.Count.ToString(CultureInfo.InvariantCulture));
