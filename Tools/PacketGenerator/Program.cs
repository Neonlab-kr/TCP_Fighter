            w.Line("public static short ReadInt16(byte[] buffer, ref int offset) { Require(buffer, offset, 2); short value = BitConverter.ToInt16(buffer, offset); offset += 2; return value; }");
            w.Line("public static ushort ReadUInt16(byte[] buffer, ref int offset) { Require(buffer, offset, 2); ushort value = BitConverter.ToUInt16(buffer, offset); offset += 2; return value; }");
