        private static void AppendC2SProxyFunction(CodeWriter w, ProtocolDef protocol, PacketDef p)
        {
            w.Line("public bool " + p.Name + "(" + CsParameterList(p.DeclaredFields, false) + ")");
            w.BeginBlock();
            w.Line("byte[] buffer = new byte[RPCCommon.HeaderSize + RPCCommon.PayloadSize_" + p.Symbol + "];");
            w.Line("int offset = 0;");
            w.Line("RPCCommon.WriteUInt8(buffer, ref offset, RPCCommon.PacketCode);");
            w.Line("RPCCommon." + protocol.Settings.PayloadSizeType.CsWrite + "(buffer, ref offset, RPCCommon.PayloadSize_" + p.Symbol + ");");
            w.Line("RPCCommon." + protocol.Settings.PacketTypeType.CsWrite + "(buffer, ref offset, RPCCommon." + p.Symbol + ");");
            for (int i = 0; i < p.DeclaredFields.Count; ++i)
                w.Line("RPCCommon." + p.DeclaredFields[i].Type.CsWrite + "(buffer, ref offset, " + p.DeclaredFields[i].Name + ");");
            w.Line("return _sender != null && _sender.SendRPCPacket(buffer);");
            w.EndBlock();
        }

        private static void AppendS2CDispatchCase(CodeWriter w, PacketDef p)
        {
            w.Line("case RPCCommon." + p.Symbol + ":");
            w.BeginBlock();
            for (int i = 0; i < p.WireFields.Count; ++i)
                w.Line(p.WireFields[i].Type.CsType + " " + p.WireFields[i].Name + ";");
            w.Line("try");
            w.BeginBlock();
            for (int i = 0; i < p.WireFields.Count; ++i)
            {
                FieldDef f = p.WireFields[i];
                w.Line(f.Name + " = RPCCommon." + f.Type.CsRead + "(buffer, ref offset);");
            }
            w.EndBlock();
            w.Line("catch");
            w.BeginBlock();
            w.Line("return false;");
            w.EndBlock();
            w.Line("return On" + p.Name + "(" + CsArgumentList(p.WireFields) + ");");
            w.EndBlock();
        }

        private static string CsParameterList(List<FieldDef> fields, bool includeOut)
        {
            StringBuilder sb = new StringBuilder();
            for (int i = 0; i < fields.Count; ++i)
            {
                if (i > 0)
                    sb.Append(", ");
                FieldDef f = fields[i];
                if (includeOut)
                    sb.Append("out ");
                sb.Append(f.Type.CsType);
                sb.Append(" ");
                sb.Append(f.Name);
            }
            return sb.ToString();
        }

        private static string CsArgumentList(List<FieldDef> fields)
        {
            StringBuilder sb = new StringBuilder();
            for (int i = 0; i < fields.Count; ++i)
            {
                if (i > 0)
                    sb.Append(", ");
                sb.Append(fields[i].Name);
            }
            return sb.ToString();
        }

        private static string CSharpLiteral(ConstDef constant)
        {
            string value = constant.Value.ToString(CultureInfo.InvariantCulture);
            if (constant.Type.CsType == "uint")
                return value + "u";
            if (constant.Type.CsType == "long")
                return value + "L";
            if (constant.Type.CsType == "ulong")
                return value + "UL";
            return value;
        }

        private static void AppendPrimitiveIO(CodeWriter w)
